#include "libft.h"

int ft_str_is_int(const char *s) {
    int i;

    if (!s || !s[0])
        return (0);
    i = 0;
    if (s[0] == '-' || s[0] == '+')
        i++;
    if (!s[i])
        return (0);
    while (s[i]) {
        if (!ft_isdigit(s[i]))
            return (0);
        i++;
    }
    return (1);
}